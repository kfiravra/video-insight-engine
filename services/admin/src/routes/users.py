class UserVideoRow(BaseModel):
    """One video generated by (or in the library of) a user."""

    userVideoId: str
    videoSummaryId: str
    youtubeId: str
    title: str | None
    channel: str | None
    duration: int | None
    thumbnailUrl: str | None
    status: str | None
    addedAt: str | None


class UserAssistantCallRow(BaseModel):
    """One LLM usage row attributed to the user from the assistant service."""

    id: str
    feature: str | None
    videoId: str | None
    model: str | None
    costUsd: float
    tokensIn: int | None
    tokensOut: int | None
    requestId: str | None
    timestamp: str
    # Cost-unit discriminator ("tokens" | "audio_seconds") — lets the UI show
    # "N min audio" for transcription rows instead of "0 tokens".
    unit: str | None = None
    audioSeconds: float | None = None


class UserCostTimelineRow(BaseModel):
    """Daily cost total for the user (from userCosts collection)."""

    date: str
    totalCostUsd: float
    creditAdjustmentUsd: float
    effectiveUsd: float


class UserActivityResponse(BaseModel):
    """Full User-360 payload: videos, assistant activity, and cost timeline."""

    userId: str
    videos: list[UserVideoRow]
    assistantCalls: list[UserAssistantCallRow]
    costTimeline: list[UserCostTimelineRow]


@router.get("/costs")
async def list_user_costs(
    days: int = Query(7, ge=1, le=MAX_DAYS),
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
) -> list[UserCostRow]:
    """Top users by effective cost over the trailing window."""
    cache_key = f"user-costs:{days}:{limit}:{offset}"
    if cache_key in _cache:
        return _cache[cache_key]

    db = get_database()
    since_key = _since_date_key(days)

    pipeline = [
        {"$match": {"date": {"$gte": since_key}}},
        {
            "$group": {
                "_id": "$userId",
                "totalCostUsd": {"$sum": "$totalCostUsd"},
                "videoCount": {"$sum": "$videoCount"},
                "creditAdjustmentUsd": {"$sum": "$creditAdjustmentUsd"},
                "days": {"$sum": 1},
            }
        },
        {
            "$addFields": {
                "effectiveUsd": {"$add": ["$totalCostUsd", "$creditAdjustmentUsd"]},
            }
        },
        {"$sort": {"effectiveUsd": -1}},
        {"$skip": offset},
        {"$limit": limit},
        {
            "$lookup": {
                "from": "users",
                "localField": "_id",
                "foreignField": "_id",
                "as": "_user",
                "pipeline": [{"$project": {"email": 1, "name": 1, "tier": 1}}],
            }
        },
        {"$unwind": {"path": "$_user", "preserveNullAndEmptyArrays": True}},
    ]

    raw = await db.userCosts.aggregate(pipeline).to_list(limit)
    data = [
        UserCostRow(
            userId=str(row["_id"]),
            email=(row.get("_user") or {}).get("email"),
            name=(row.get("_user") or {}).get("name"),
            tier=(row.get("_user") or {}).get("tier") or "free",
            totalCostUsd=row["totalCostUsd"],
            videoCount=row["videoCount"],
            creditAdjustmentUsd=row["creditAdjustmentUsd"],
            effectiveUsd=row["effectiveUsd"],
            days=row["days"],
        )
        for row in raw
    ]
    _cache[cache_key] = data
    return data


@router.get("/{user_id}/costs")
async def user_cost_detail(
    user_id: str = Path(..., min_length=24, max_length=24),
    days: int = Query(30, ge=1, le=MAX_DAYS),
) -> UserCostDetail:
    """Per-user daily breakdown + recent adjustments."""
    user_oid = _parse_object_id(user_id)
    db = get_database()
    since_key = _since_date_key(days)

    user_doc = await db.users.find_one(
        {"_id": user_oid},
        {"email": 1, "name": 1, "tier": 1},
    )

    daily_cursor = db.userCosts.find(
        {"userId": user_oid, "date": {"$gte": since_key}},
    ).sort("date", 1)
    daily_docs = await daily_cursor.to_list(MAX_DAYS)

    daily_rows: list[UserDailyRow] = []
    raw_total = 0.0
    raw_credit = 0.0
    video_count = 0
    for doc in daily_docs:
        total = float(doc.get("totalCostUsd", 0) or 0)
        credit = float(doc.get("creditAdjustmentUsd", 0) or 0)
        videos = int(doc.get("videoCount", 0) or 0)
        raw_total += total
        raw_credit += credit
        video_count += videos
        daily_rows.append(
            UserDailyRow(
                date=doc["date"],
                totalCostUsd=total,
                videoCount=videos,
                creditAdjustmentUsd=credit,
                effectiveUsd=total + credit,
            )
        )

    summary = UserCostRow(
        userId=user_id,
        email=(user_doc or {}).get("email"),
        name=(user_doc or {}).get("name"),
        tier=(user_doc or {}).get("tier") or "free",
        totalCostUsd=raw_total,
        videoCount=video_count,
        creditAdjustmentUsd=raw_credit,
        effectiveUsd=raw_total + raw_credit,
        days=len(daily_rows),
    )

    adj_cursor = db.userCostAdjustments.find({"userId": user_oid}).sort("createdAt", -1).limit(20)
    adjustments_raw = await adj_cursor.to_list(20)
    adjustments = [
        {
            "id": str(a["_id"]),
            "date": a.get("date"),
            "amountUsd": float(a.get("amountUsd", 0) or 0),
            "reason": a.get("reason"),
            "adminId": str(a["adminId"]) if a.get("adminId") else None,
            "createdAt": a.get("createdAt").isoformat() if a.get("createdAt") else None,
        }
        for a in adjustments_raw
    ]

    return UserCostDetail(user=summary, daily=daily_rows, adjustments=adjustments)


@router.post("/{user_id}/grant-credit")
async def grant_credit(
    user_id: Annotated[str, Path(pattern=OBJECT_ID_PATTERN)],
    body: GrantCreditRequest,
    actor: Annotated[AdminActor, Depends(current_user_actor)],
    idempotency_key: Annotated[
        str | None, Header(alias="Idempotency-Key", pattern=IDEMPOTENCY_KEY_PATTERN)
    ] = None,
) -> dict:
    """Grant minutes: a proxy to vie-api's ``POST /api/admin/billing/accounts/{id}/credits``.

    vie-api is the only writer of the minutes ledger. It creates the credit lot,
    stamps the ledger entry and the ``adminAudit`` row with the admin named by
    the signed session (never a body field) and the reason, and returns
    ``{before, after, lotId, auditId}``. Send a stable ``Idempotency-Key`` per
    form submission so a retry after a timeout cannot grant twice. The old
    dollar credit (``userCosts`` / ``userCostAdjustments``) is read-only
    history now; nothing here writes it.
    """
    logger.info(
        "credit_grant_requested user=%s admin=%s minutes=%d", user_id, actor.user_id, body.minutes
    )
    return await call_vie_api(
        "POST",
        f"billing/accounts/{user_id}/credits",
        actor,
        body=body.model_dump(mode="json", exclude_none=True),
        idempotency_key=idempotency_key,
    )


def _format_user_video(doc: dict) -> UserVideoRow:
    """Map a userVideos document to a UserVideoRow."""
    added_at = doc.get("addedAt")
    return UserVideoRow(
        userVideoId=str(doc["_id"]),
        videoSummaryId=str(doc["videoSummaryId"]),
        youtubeId=doc.get("youtubeId", ""),
        title=doc.get("title"),
        channel=doc.get("channel"),
        duration=doc.get("duration"),
        thumbnailUrl=doc.get("thumbnailUrl"),
        status=doc.get("status"),
        addedAt=added_at.isoformat() if isinstance(added_at, datetime) else None,
    )


def _format_assistant_call(doc: dict) -> UserAssistantCallRow:
    """Map an llm_usage document to a UserAssistantCallRow."""
    ts = doc.get("timestamp")
    return UserAssistantCallRow(
        id=str(doc["_id"]),
        feature=doc.get("feature"),
        videoId=doc.get("video_id"),
        model=doc.get("model"),
        costUsd=float(doc.get("cost_usd") or 0),
        tokensIn=doc.get("tokens_in"),
        tokensOut=doc.get("tokens_out"),
        requestId=doc.get("request_id"),
        timestamp=ts.isoformat() if isinstance(ts, datetime) else str(ts or ""),
        unit=doc.get("unit"),
        audioSeconds=doc.get("audio_seconds"),
    )


@router.get("/{user_id}/activity", response_model=UserActivityResponse)
async def user_activity(
    user_id: str = Path(..., min_length=24, max_length=24),
    days: int = Query(30, ge=1, le=MAX_DAYS),
) -> UserActivityResponse:
    """User-360: videos generated, assistant LLM calls, and daily cost timeline.

    Video ownership is resolved via the ``userVideos`` collection
    (``userId`` + ``videoSummaryId`` join). Assistant activity is sourced
    from ``llm_usage`` rows where ``user_id`` matches. Cost timeline comes
    from the ``userCosts`` daily aggregate. All three queries run in
    parallel.
    """
    user_oid = _parse_object_id(user_id)
    since_key = _since_date_key(days)
    db = get_database()

    user_videos_cursor = (
        db.userVideos.find(
            {"userId": user_oid},
            {
                "videoSummaryId": 1,
                "youtubeId": 1,
                "title": 1,
                "channel": 1,
                "duration": 1,
                "thumbnailUrl": 1,
                "status": 1,
                "addedAt": 1,
            },
        )
        .sort("addedAt", -1)
        .limit(100)
    )

    assistant_since = datetime.now(UTC) - timedelta(days=days)
    assistant_cursor = (
        db.llm_usage.find(
            {"user_id": user_id, "timestamp": {"$gte": assistant_since}},
            {"prompt_preview": 0},
        )
        .sort("timestamp", -1)
        .limit(200)
    )

    cost_cursor = db.userCosts.find(
        {"userId": user_oid, "date": {"$gte": since_key}},
    ).sort("date", 1)

    video_docs, assistant_docs, cost_docs = await asyncio.gather(
        user_videos_cursor.to_list(100),
        assistant_cursor.to_list(200),
        cost_cursor.to_list(MAX_DAYS),
    )

    videos = [_format_user_video(d) for d in video_docs]

    assistant_calls = [_format_assistant_call(d) for d in assistant_docs]

    cost_timeline = [
        UserCostTimelineRow(
            date=d["date"],
            totalCostUsd=float(d.get("totalCostUsd") or 0),
            creditAdjustmentUsd=float(d.get("creditAdjustmentUsd") or 0),
            effectiveUsd=float(d.get("totalCostUsd") or 0)
            + float(d.get("creditAdjustmentUsd") or 0),
        )
        for d in cost_docs
    ]

    return UserActivityResponse(
        userId=user_id,
        videos=videos,
        assistantCalls=assistant_calls,
        costTimeline=cost_timeline,
    )
