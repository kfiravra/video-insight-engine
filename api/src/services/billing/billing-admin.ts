import { ObjectId } from 'mongodb';
import { z } from 'zod';
import { MIN_MINUTES_PER_VIDEO, PAID_MAX_VIDEO_MINUTES, PLAN_IDS } from '@vie/types';
import { NotFoundError, ValidationError } from '../../utils/errors.js';
import { applyAdjust, applyGrantLot, applySetCaps, applySetPlan, capsAlreadyApplied } from './admin-ops.js';
import { parseObjectId } from './billing-unit.js';
import { MAX_ADMIN_MINUTES } from './minutes.js';
import { toHoldView, toLedgerView, toLotView, toRecurringGrantView, toSnapshot } from './views.js';
import type { ClientSession } from 'mongodb';
import type { AccountCaps, AccountDetail, AccountSnapshot, PlanId } from '@vie/types';
import type { AccountDraft } from './account-draft.js';
import type { AdminAudit } from './admin-ops.js';
import type { BillingUnits } from './billing-unit.js';
import type { BillingRepository, RecurringGrantDocument } from '../../repositories/billing.repository.js';
import type { UserRepository } from '../../repositories/user.repository.js';

// Contract 1 (lanes.md): the admin API of BillingService. The route writes
// the `adminAudit` row with the same `auditId` after this returns; nothing
// here writes audit rows. A retried call with the same auditId is a no-op.

export interface AdminMutationContext {
  /** users._id hex of the admin, or 'system:<name>'. */
  actorId: string;
  /** 1–500 chars. */
  reason: string;
  /** ObjectId hex pre-generated by the caller; ledger key `admin:<auditId>[:<suffix>]`. */
  auditId: string;
}

export interface MutationResult<T> {
  before: T;
  after: T;
}

export interface AccountDetailOptions {
  ledgerLimit?: number;
  ledgerBefore?: Date;
}

const DEFAULT_LEDGER_LIMIT = 50;
const ADMIN_LOT_LIMIT = 100;
const adminMinutes = z.number().int().min(1).max(MAX_ADMIN_MINUTES);

const contextSchema = z.object({
  actorId: z.string().trim().min(1).max(200),
  reason: z.string().trim().min(1, 'reason is required').max(500),
  auditId: z.string().regex(/^[0-9a-f]{24}$/i, 'auditId must be a 24-character hex id'),
});
const setPlanSchema = z.object({ planId: z.enum(PLAN_IDS), periodEnd: z.date().optional() }).strict();
const grantLotSchema = z.object({ minutes: adminMinutes, expiresAt: z.date().nullable().optional() }).strict();
// Caps only tighten (a cap above the paid maximum would change nothing).
const capsSchema = z
  .object({
    maxVideoMinutes: z.number().int().min(MIN_MINUTES_PER_VIDEO).max(PAID_MAX_VIDEO_MINUTES).nullable().optional(),
    freeVideosPerDay: z.number().int().min(0).max(100).nullable().optional(),
    maxConcurrent: z.number().int().min(1).max(1000).nullable().optional(),
    blocked: z.boolean().nullable().optional(),
  })
  .strict()
  .refine((caps) => Object.values(caps).some((value) => value !== undefined), 'at least one cap is required');
const adjustSchema = z
  .object({
    bucket: z.enum(['plan', 'credit']),
    minutes: z.number().int().min(-MAX_ADMIN_MINUTES).max(MAX_ADMIN_MINUTES).refine((m) => m !== 0, 'minutes must not be 0'),
  })
  .strict();
const recurringGrantSchema = z.object({ minutes: adminMinutes, every: z.literal('month'), active: z.boolean() }).strict();
const detailSchema = z
  .object({ ledgerLimit: z.number().int().min(1).max(200).optional(), ledgerBefore: z.date().optional() })
  .strict();

/** Schema check that throws the API's own ValidationError (not a raw ZodError). */
function parse<T>(schema: z.ZodType<T, z.ZodTypeDef, unknown>, value: unknown): T {
  const result = schema.safeParse(value);
  if (result.success) return result.data;
  const issue = result.error.errors[0];
  const path = issue?.path.join('.');
  throw new ValidationError(path ? `${path}: ${issue.message}` : (issue?.message ?? 'Invalid input'));
}

function parseContext(ctx: AdminMutationContext): AdminAudit {
  const { actorId, reason, auditId } = parse(contextSchema, ctx);
  return { actorId, reason, auditId: new ObjectId(auditId) };
}

interface AdminStep {
  draft: AccountDraft;
  audit: AdminAudit;
  session: ClientSession;
  /** True when entries for this auditId already exist (a retried call). */
  replay: boolean;
}

export class BillingAdmin {
  constructor(
    private readonly repo: BillingRepository,
    private readonly units: BillingUnits,
    private readonly userRepository: UserRepository,
  ) {}

  async getAccountDetail(userId: string, opts: AccountDetailOptions = {}): Promise<AccountDetail> {
    const { ledgerLimit = DEFAULT_LEDGER_LIMIT, ledgerBefore } = parse(detailSchema, opts);
    await this.requireUser(userId);
    const draft = await this.units.read(userId);
    const lots = await this.repo.listLots(draft.accountId, ADMIN_LOT_LIMIT);
    const ledger = await this.repo.listLedger(draft.accountId, { limit: ledgerLimit, before: ledgerBefore });
    const grants = await this.repo.listRecurringGrants(draft.accountId);
    return {
      account: toSnapshot(draft.account, draft.lots, draft.now),
      lots: lots.map((lot) => toLotView(lot, draft.now)),
      holds: draft.account.holds.map(toHoldView),
      ledger: ledger.map(toLedgerView),
      recurringGrants: grants.map(toRecurringGrantView),
    };
  }

  async setPlan(
    userId: string,
    input: { planId: PlanId; periodEnd?: Date },
    ctx: AdminMutationContext,
  ): Promise<MutationResult<AccountSnapshot>> {
    const plan = parse(setPlanSchema, input);
    return this.mutate(userId, ctx, async ({ draft, audit, replay }) => {
      if (!replay) applySetPlan(draft, plan, audit);
    });
  }

  async grantLot(
    userId: string,
    input: { minutes: number; expiresAt?: Date | null },
    ctx: AdminMutationContext,
  ): Promise<MutationResult<AccountSnapshot> & { lotId: string }> {
    const grant = parse(grantLotSchema, input);
    const { value, ...result } = await this.mutate(userId, ctx, async ({ draft, audit, replay, session }) => {
      if (!replay) return applyGrantLot(draft, grant, audit);
      const [entry] = await this.repo.findLedgerByKeys([`admin:${audit.auditId.toHexString()}`], session);
      if (!entry?.lotId) throw new ValidationError('auditId was already used for a different change');
      return entry.lotId;
    });
    return { ...result, lotId: value.toHexString() };
  }

  async setCaps(userId: string, caps: Partial<AccountCaps>, ctx: AdminMutationContext): Promise<MutationResult<AccountSnapshot>> {
    const patch = parse(capsSchema, caps);
    return this.mutate(userId, ctx, async ({ draft, audit }) => {
      // A retry of an applied change must not undo a newer one (I1).
      if (!capsAlreadyApplied(draft, audit)) applySetCaps(draft, patch, audit);
    });
  }

  async adjust(
    userId: string,
    input: { bucket: 'plan' | 'credit'; minutes: number },
    ctx: AdminMutationContext,
  ): Promise<MutationResult<AccountSnapshot>> {
    const adjustment = parse(adjustSchema, input);
    return this.mutate(userId, ctx, async ({ draft, audit, replay }) => {
      if (!replay) applyAdjust(draft, adjustment, audit);
    });
  }

  async createRecurringGrant(
    userId: string,
    input: { minutes: number; every: 'month'; active: boolean },
    ctx: AdminMutationContext,
  ): Promise<MutationResult<AccountSnapshot> & { grantId: string }> {
    const spec = parse(recurringGrantSchema, input);
    const { value, ...result } = await this.mutate(userId, ctx, async ({ draft, audit, session }) => {
      const existing = await this.repo.findRecurringGrantByAudit(draft.accountId, audit.auditId, session);
      if (existing) return existing._id;
      const grant: RecurringGrantDocument = {
        _id: new ObjectId(), accountId: draft.accountId, ...spec,
        // First run on the next repair tick: the account gets its minutes now, then monthly.
        nextRunAt: draft.now, lastRunAt: null,
        actorId: audit.actorId, auditId: audit.auditId, reason: audit.reason,
        createdAt: draft.now, updatedAt: draft.now, deletedAt: null,
      };
      await this.repo.insertRecurringGrant(grant, session);
      return grant._id;
    });
    return { ...result, grantId: value.toHexString() };
  }

  async deleteRecurringGrant(userId: string, grantId: string, ctx: AdminMutationContext): Promise<MutationResult<AccountSnapshot>> {
    const id = parseObjectId(grantId, 'grantId');
    return this.mutate(userId, ctx, async ({ draft, session }) => {
      const grant = await this.repo.findRecurringGrant(draft.accountId, id, session);
      if (!grant) throw new NotFoundError('Recurring grant');
      if (!grant.deletedAt) await this.repo.softDeleteRecurringGrant(id, draft.now, session);
    });
  }

  private async requireUser(userId: string): Promise<void> {
    parseObjectId(userId, 'userId');
    const user = await this.userRepository.findById(userId);
    if (!user) throw new NotFoundError('User');
  }

  /** Validate, check the user, run `op` in a billing unit, and snapshot the account before and after. */
  private async mutate<T>(
    userId: string,
    ctx: AdminMutationContext,
    op: (step: AdminStep) => Promise<T>,
  ): Promise<MutationResult<AccountSnapshot> & { value: T }> {
    const audit = parseContext(ctx);
    await this.requireUser(userId);
    const outcome = await this.units.write(userId, async ({ draft, session }) => {
      const before = toSnapshot(draft.account, draft.lots, draft.now);
      const prior = await this.repo.findLedgerBySourceRef(audit.auditId.toHexString(), session);
      const value = await op({ draft, audit, session, replay: prior.length > 0 });
      return { before, value, now: draft.now };
    });
    const { before, value, now } = outcome.value;
    return { before, after: toSnapshot(outcome.account, outcome.lots, now), value };
  }
}
